import json
import logging
from typing import Any, Dict, List, Optional, Tuple

logger = logging.getLogger("notification_service.extractor")

def extract_clean_adk_response(adk_response_payload: Any) -> Tuple[str, Dict[str, Any]]:
    """
    Extracts strictly the final human-readable assistant message from Google ADK response events,
    filtering out function_call (SQL), function_response (raw DB rows), and model thought traces.

    Returns:
        Tuple of (clean_text_response: str, metadata: dict)
    """
    metadata: Dict[str, Any] = {
        "tokens": {"prompt": 0, "completion": 0, "total": 0},
        "author": "assistant",
        "has_tables": False
    }

    if not adk_response_payload:
        return "", metadata

    events: List[Dict[str, Any]] = []

    # Case 1: Payload is a string (JSON string, JSONL, or plain text)
    if isinstance(adk_response_payload, str):
        payload_str = adk_response_payload.strip()
        try:
            parsed = json.loads(payload_str)
            if isinstance(parsed, list):
                events = parsed
            elif isinstance(parsed, dict):
                events = parsed.get("events", [parsed])
            else:
                return payload_str, metadata
        except Exception:
            # Check for JSONL (multiple JSON objects separated by newline)
            lines = [line.strip() for line in payload_str.split("\n") if line.strip()]
            for line in lines:
                try:
                    obj = json.loads(line)
                    if isinstance(obj, dict):
                        events.append(obj)
                except Exception:
                    pass
            if not events:
                # If cannot be parsed as JSON, return raw text
                return payload_str, metadata

    # Case 2: Payload is already a list of event dictionaries
    elif isinstance(adk_response_payload, list):
        events = adk_response_payload

    # Case 3: Payload is a dictionary containing an 'events' list or single event
    elif isinstance(adk_response_payload, dict):
        if "events" in adk_response_payload and isinstance(adk_response_payload["events"], list):
            events = adk_response_payload["events"]
        elif "text" in adk_response_payload and isinstance(adk_response_payload["text"], str):
            return adk_response_payload["text"].strip(), metadata
        else:
            events = [adk_response_payload]

    final_text_blocks: List[str] = []

    for event in events:
        if not isinstance(event, dict):
            continue

        # Accumulate token usage metrics if present
        usage = event.get("usageMetadata")
        if isinstance(usage, dict):
            metadata["tokens"]["prompt"] += usage.get("promptTokenCount", 0) or 0
            metadata["tokens"]["completion"] += usage.get("candidatesTokenCount", 0) or 0
            metadata["tokens"]["total"] += usage.get("totalTokenCount", 0) or 0

        # Check content block
        content = event.get("content")
        if not content or not isinstance(content, dict):
            # Fallback check for direct text on event
            if "text" in event and isinstance(event["text"], str):
                final_text_blocks.append(event["text"].strip())
            continue

        parts = content.get("parts", [])
        if not isinstance(parts, list):
            continue

        for part in parts:
            if not isinstance(part, dict):
                continue

            # 1. Filter out tool requests (SQL statements generated by agent)
            if part.get("function_call"):
                continue

            # 2. Filter out tool execution responses (Raw database JSON rows)
            if part.get("function_response"):
                continue

            # 3. Filter out internal model thinking / chain-of-thought traces
            if part.get("thought"):
                continue

            # 4. Extract clean human-facing text
            text_chunk = part.get("text", "")
            if text_chunk and isinstance(text_chunk, str):
                cleaned_chunk = text_chunk.strip()
                if cleaned_chunk:
                    # Avoid appending duplicate consecutive messages
                    if not final_text_blocks or final_text_blocks[-1] != cleaned_chunk:
                        final_text_blocks.append(cleaned_chunk)

    clean_text = "\n\n".join(final_text_blocks).strip()

    # Detect if response contains markdown table
    if "|" in clean_text and "\n|---" in clean_text or "\n| ---" in clean_text or "\n|:-" in clean_text:
        metadata["has_tables"] = True

    return clean_text, metadata


def extract_clean_text_only(adk_response_payload: Any) -> str:
    """
    Convenience helper that returns strictly the extracted text string.
    """
    clean_text, _ = extract_clean_adk_response(adk_response_payload)
    return clean_text

